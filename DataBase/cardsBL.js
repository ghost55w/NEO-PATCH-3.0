function determinePrice(rank) {
  const rankPrices = { "SS": 3000000, "S": 1000000, "A": 500000, "B": 100000 };
  return rankPrices[rank] || 0;
}

// --------------------
// 🔵 CATÉGORIE SELON OVR
// --------------------
function determineCategory(ovr) {
  if (ovr >= 100) return "world_class";
  if (ovr >= 90) return "next_gen";
  if (ovr >= 80) return "rare";
  return "normal";
}

// --------------------
// 🔵 CRÉATION D’UNE CARD
// --------------------
function createCardFromBlueLock(data) {
  return {
    name: data.name,
    country: data.country,
    ovr: data.ovr,
    sho: data.sho,
    dri: data.dri,
    pas: data.pas,
    acc: data.acc,
    phy: data.phy,
    def: data.def,
    goal: data.goal || "",
    image: data.image,
    pictures: data.pictures || [],
    weapons: data.weapons || [],
    attitude: data.attitude || "calme",
    rank: data.rank,
    taille: data.taille,
    pieds: data.pieds,
    category: determineCategory(data.ovr),
    price: determinePrice(data.rank) + (data.ovr * 1000),
    placement:
      data.rank === "SS"
        ? "elite"
        : data.rank === "S"
        ? "world_class"
        : "normal"
  };
}

// --------------------
// 🔵 RECHERCHE PAR NAME
// --------------------
function findPlayerByName(input, cardsObject) {
  const search = input.toLowerCase();
  return Object.values(cardsObject).find(player =>
    player.name.toLowerCase().includes(search)
  );
}

// --------------------
// 🔵 GROUPER PAR PLACEMENT (SANS goal)
// --------------------
function groupCardsByPlacement(cardsArray) {
  const grouped = {};
  for (const card of cardsArray) {
    const place = card.placement;
    if (!grouped[place]) grouped[place] = [];

    grouped[place].push({
      name: card.name,
      country: card.country,
      rank: card.rank,
      ovr: card.ovr,
      category: card.category,
      image: card.image,
      price: card.price,
      taille: card.taille,
      pieds: card.pieds,
      attitude: card.attitude,
      pictures: card.pictures
    });
  }
  return grouped;
}

// --------------------
// 🔵 GÉNÉRER TOUTES LES CARTES
// --------------------
function generateCardsFromBlueLock(cardsObject) {
  const all = [];
  for (const player of Object.values(cardsObject)) {
    all.push(createCardFromBlueLock(player));
  }
  return groupCardsByPlacement(all);
}

